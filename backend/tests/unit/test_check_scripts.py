# ---------------------------------------------------------------------------
# Sign-off: the author's, or that of whoever committed their work
# ---------------------------------------------------------------------------

DCO = ROOT / "scripts" / "check-dco.sh"


def _repository(tmp_path: Path) -> Path:
    """A repository of its own, with the check sitting where it expects to."""
    repository = tmp_path / "repository"
    (repository / "scripts").mkdir(parents=True)
    (repository / "scripts" / "check-dco.sh").write_bytes(DCO.read_bytes())
    (repository / "scripts" / "check-dco.sh").chmod(0o755)
    subprocess.run(["git", "init", "-q", "-b", "main", str(repository)], check=True)
    # A commit to branch from, so that a range can be written at all.
    _commit(repository, "the beginning\n\nSigned-off-by: " + MAINTAINER, MAINTAINER, MAINTAINER)
    return repository


def _commit(repository: Path, message: str, author: str, committer: str) -> None:
    (repository / "file").write_text(message, encoding="utf-8")
    name, _, email = author.partition(" <")
    committer_name, _, committer_email = committer.partition(" <")
    environment = dict(
        os.environ,
        GIT_AUTHOR_NAME=name,
        GIT_AUTHOR_EMAIL=email.rstrip(">"),
        GIT_COMMITTER_NAME=committer_name,
        GIT_COMMITTER_EMAIL=committer_email.rstrip(">"),
    )
    subprocess.run(["git", "add", "file"], cwd=repository, check=True, env=environment)
    subprocess.run(
        ["git", "commit", "-q", "-m", message], cwd=repository, check=True, env=environment
    )


def _check(repository: Path, *arguments):
    return subprocess.run(
        [str(repository / "scripts" / "check-dco.sh"), *arguments],
        capture_output=True,
        text=True,
        cwd=str(repository),
    )


MAINTAINER = "A Maintainer <maintainer@example.com>"
BOT = "dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>"


@pytest.mark.io
def test_the_author_signing_off_is_the_ordinary_case(tmp_path):
    repository = _repository(tmp_path)
    _commit(repository, "a change\n\nSigned-off-by: " + MAINTAINER, MAINTAINER, MAINTAINER)

    result = _check(repository, "HEAD~1..HEAD")

    assert result.returncode == 0, result.stdout + result.stderr
    assert "All 1 commit(s)" in result.stdout


@pytest.mark.io
def test_the_committer_may_sign_off_for_work_they_took_over(tmp_path):
    # `git cherry-pick -s` on a Dependabot commit, as CONTRIBUTING.md
    # describes it: the bot stays the author, the maintainer certifies.
    repository = _repository(tmp_path)
    _commit(repository, "backend: bump black\n\nSigned-off-by: " + MAINTAINER, BOT, MAINTAINER)

    result = _check(repository, "HEAD~1..HEAD")

    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.io
def test_a_sign_off_by_neither_of_them_is_not_a_sign_off(tmp_path):
    repository = _repository(tmp_path)
    _commit(
        repository,
        "backend: bump black\n\nSigned-off-by: Someone Else <else@example.com>",
        BOT,
        BOT,
    )

    result = _check(repository, "HEAD~1..HEAD")

    assert result.returncode != 0
    assert "dependabot[bot]" in result.stdout


@pytest.mark.io
def test_a_branch_that_adds_nothing_has_nothing_to_certify(tmp_path):
    repository = _repository(tmp_path)
    _commit(repository, "a change\n\nSigned-off-by: " + MAINTAINER, MAINTAINER, MAINTAINER)

    defaulted = _check(repository)
    asked_for = _check(repository, "HEAD..HEAD")

    assert defaulted.returncode == 0, defaulted.stdout + defaulted.stderr
    assert "nothing to certify" in defaulted.stdout
    assert asked_for.returncode != 0
